-- Создание схем и таблиц проекта.

CREATE SCHEMA IF NOT EXISTS :"stg_schema";
CREATE SCHEMA IF NOT EXISTS :"ods_schema";
CREATE SCHEMA IF NOT EXISTS :"datamart_schema";

CREATE TABLE IF NOT EXISTS :"stg_schema".etl_load_log (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dag_id              text NOT NULL,
    task_id             text NOT NULL,
    source              text NOT NULL,
    target_table        text NOT NULL,
    ds                  date NOT NULL,
    started_at          timestamptz NOT NULL DEFAULT now(),
    finished_at         timestamptz,
    status              text NOT NULL DEFAULT 'running'
                        CHECK (status IN ('running', 'success', 'failed')),
    rows_loaded         bigint NOT NULL DEFAULT 0 CHECK (rows_loaded >= 0),
    error_text          text
);

CREATE INDEX IF NOT EXISTS etl_load_log_ds_idx
    ON :"stg_schema".etl_load_log (ds, started_at DESC);

-- Staging: исходные значения сохраняются как текст.
CREATE TABLE IF NOT EXISTS :"stg_schema".stg_federal_transactions (
    award_id_piid               text,
    modification_number         text,
    action_date                 text,
    federal_action_obligation   text,
    awarding_agency_code        text,
    awarding_agency_name        text,
    recipient_name              text,
    award_type_code             text,
    award_type                  text,
    _ds                         date NOT NULL,
    _source_file                text NOT NULL,
    _loaded_at                  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS :"stg_schema".stg_award_type_reference (
    award_type_code     text,
    award_type_group    text,
    award_type_name     text,
    _ds                 date NOT NULL,
    _source_file        text NOT NULL,
    _loaded_at          timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS :"stg_schema".stg_api_awards (
    award_id                    text,
    recipient_id                text,
    recipient_name              text,
    awarding_agency_code        text,
    awarding_agency_name        text,
    start_date                  text,
    award_amount                text,
    contract_award_type         text,
    _ds                         date NOT NULL,
    _source_file                text NOT NULL,
    _loaded_at                  timestamptz NOT NULL DEFAULT now()
);

-- ODS-справочники создаются перед таблицами, которые на них ссылаются.
CREATE TABLE IF NOT EXISTS :"ods_schema".ods_agencies (
    agency_code     text PRIMARY KEY,
    agency_name     text NOT NULL
);

CREATE TABLE IF NOT EXISTS :"ods_schema".ods_recipients (
    recipient_id    text PRIMARY KEY,
    recipient_name  text NOT NULL
);

CREATE TABLE IF NOT EXISTS :"ods_schema".ods_award_types (
    award_type_code   text PRIMARY KEY,
    award_type_group  text NOT NULL,
    award_type_name   text NOT NULL
);

CREATE TABLE IF NOT EXISTS :"ods_schema".ods_awards (
    award_id          text PRIMARY KEY,
    recipient_id      text,
    agency_code       text NOT NULL,
    award_type_code   text NOT NULL,
    start_date        date,
    award_amount      numeric(20, 2),
    CONSTRAINT ods_awards_recipient_fk
        FOREIGN KEY (recipient_id)
        REFERENCES :"ods_schema".ods_recipients (recipient_id),
    CONSTRAINT ods_awards_agency_fk
        FOREIGN KEY (agency_code)
        REFERENCES :"ods_schema".ods_agencies (agency_code),
    CONSTRAINT ods_awards_type_fk
        FOREIGN KEY (award_type_code)
        REFERENCES :"ods_schema".ods_award_types (award_type_code)
);

CREATE TABLE IF NOT EXISTS :"ods_schema".ods_federal_transactions (
    award_id_piid               text NOT NULL,
    modification_number         text NOT NULL,
    action_date                 date NOT NULL,
    federal_action_obligation   numeric(20, 2) NOT NULL,
    awarding_agency_code        text NOT NULL,
    award_type_code             text NOT NULL,
    CONSTRAINT ods_federal_transactions_pk
        PRIMARY KEY (award_id_piid, modification_number),
    CONSTRAINT ods_federal_transactions_award_fk
        FOREIGN KEY (award_id_piid)
        REFERENCES :"ods_schema".ods_awards (award_id),
    CONSTRAINT ods_federal_transactions_agency_fk
        FOREIGN KEY (awarding_agency_code)
        REFERENCES :"ods_schema".ods_agencies (agency_code),
    CONSTRAINT ods_federal_transactions_type_fk
        FOREIGN KEY (award_type_code)
        REFERENCES :"ods_schema".ods_award_types (award_type_code)
);

CREATE INDEX IF NOT EXISTS ods_federal_transactions_date_idx
    ON :"ods_schema".ods_federal_transactions (action_date);

CREATE INDEX IF NOT EXISTS ods_federal_transactions_agency_date_idx
    ON :"ods_schema".ods_federal_transactions
       (awarding_agency_code, action_date);

CREATE INDEX IF NOT EXISTS ods_awards_start_date_idx
    ON :"ods_schema".ods_awards (start_date);

-- Денормализованные витрины: одна таблица отвечает на один бизнес-вопрос.
CREATE TABLE IF NOT EXISTS :"datamart_schema".dm_agency_daily_spending (
    action_date                 date NOT NULL,
    agency_code                 text NOT NULL,
    agency_name                 text NOT NULL,
    transaction_count           bigint NOT NULL,
    awards_count                bigint NOT NULL,
    net_action_obligation       numeric(20, 2) NOT NULL,
    built_at                    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (action_date, agency_code)
);

CREATE TABLE IF NOT EXISTS :"datamart_schema".dm_recipient_analysis (
    period_start                date NOT NULL,
    period_end                  date NOT NULL,
    recipient_id                text NOT NULL,
    recipient_name              text NOT NULL,
    transaction_count           bigint NOT NULL,
    awards_count                bigint NOT NULL,
    net_action_obligation       numeric(20, 2) NOT NULL,
    rank_by_obligation          bigint NOT NULL,
    rank_by_awards              bigint NOT NULL,
    built_at                    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (period_start, recipient_id)
);

CREATE INDEX IF NOT EXISTS dm_agency_daily_spending_agency_idx
    ON :"datamart_schema".dm_agency_daily_spending (agency_code, action_date);

CREATE INDEX IF NOT EXISTS dm_recipient_analysis_rank_idx
    ON :"datamart_schema".dm_recipient_analysis
       (period_start, rank_by_obligation);
